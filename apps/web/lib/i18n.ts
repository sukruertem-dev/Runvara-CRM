export type Locale = 'tr' | 'en';

const catalogs: Record<Locale, Record<MessageKey, string>> = { tr, en };
let current: Locale = 'tr';

export function setLocale(locale: Locale): void {
  current = locale;
}

export function t(key: MessageKey, vars?: Record<string, string>): string {
  let text: string = catalogs[current][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
  }
  return text;
}

/** Looks up a key that is only known at runtime (API codes, role keys, module name keys). */
export function tOptional(key: string): string | undefined {
  return Object.hasOwn(tr, key) ? t(key as MessageKey) : undefined;
}

export function roleLabel(roleKey: string): string {
  return tOptional(`role.${roleKey}`) ?? roleKey;
}

/** Accepts either a module id (`crm`) or a display name key (`module.crm.name`). */
export function moduleLabel(moduleKeyOrId: string): string {
  const key = moduleKeyOrId.startsWith('module.') ? moduleKeyOrId : `module.${moduleKeyOrId}.name`;
  return tOptional(key) ?? moduleKeyOrId;
}
